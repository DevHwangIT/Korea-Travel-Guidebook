def build_lang(lang: str) -> dict:
    incheon = dict(CHROME[lang])
    incheon["courses"] = {cid: COURSES[cid][lang] for cid in COURSES}
    return incheon


def main() -> None:
    for lang in LANGS:
        path = ROOT / "i18n" / "pages" / "travel-courses" / f"{lang}.json"
        with path.open(encoding="utf-8") as f:
            data = json.load(f)
        curated = data.setdefault("travelCourses", {}).setdefault("curated", {})
        curated["incheon"] = build_lang(lang)
        with path.open("w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print("updated", path.relative_to(ROOT), "courses", len(curated["incheon"]["courses"]))


if __name__ == "__main__":
    main()
